/// The guest's own config copy (seeded, then the guest's), the reference copy (rewritten every
/// start) and the README explaining them; inside the guest directory, under the guest home.
pub const GUEST_CONFIG_DIRECTORY: &str = "home/amoeboid";
pub const GUEST_OWN_CONFIG: &str = "home/amoeboid/nix";
pub const GUEST_REFERENCE_CONFIG: &str = "home/amoeboid/reference";

pub const GUEST_README: &str = "\
# This VM's NixOS configuration

- `nix/` is your own copy of the configuration this VM was created from: the flake,
  `base.nix` (user, shares, ssh, console), `recipe.nix` (packages, services, tweaks)
  and `host.nix` (your account, generated by the host and passed in as the `host` input).
  Edit it freely; amoeboid never overwrites or reads it. Changes there are not applied
  automatically: whoever runs this VM decides when and how to adopt them.
- `reference/` is the configuration this VM is actually running. It is rewritten on
  every start, so edits there are lost; diff your copy against it to see your changes.

The Nix store is read-only inside this VM, so nothing can be installed through Nix from
here, and anything installed outside your home directory is gone after a restart. Find
packages with `nixpkgs-search REGEX` (it searches the exact nixpkgs this VM uses), then
add them to `nix/recipe.nix`.
";

/// How often the sshd banner is probed while waiting.
const PROBE_INTERVAL: Duration = Duration::from_secs(1);

#[derive(Debug)]
pub enum GuestVmCommand {
    Prepare {
        generation: Generation,
        vm: VmPaths,
        spec: Box<VmSpec>,
        /// Write the guest's own config copy: on a VM's first start and on a rebase.
        seed_own_config: bool,
    },
    /// Probe for the sshd banner until it answers or `timeout_seconds` pass.
    AwaitSsh {
        generation: Generation,
        port: LoopbackPort,
        timeout_seconds: u32,
    },
}

#[derive(Debug)]
pub enum GuestVmObservation {
    Prepared {
        generation: Generation,
        port: LoopbackPort,
        host_key: HostPublicKey,
    },
    PrepareFailed {
        generation: Generation,
        reason: Report,
    },
    SshReady {
        generation: Generation,
    },
    SshTimedOut {
        generation: Generation,
    },
}

#[derive(Debug, thiserror::Error)]
pub enum GuestVmError {
    #[error(transparent)]
    Ssh(#[from] SshError),
    #[error(transparent)]
    Guest(#[from] GuestError),
    #[error(transparent)]
    File(#[from] FileError),
    #[error(transparent)]
    Path(#[from] BadRelativePath),
    #[error(transparent)]
    Home(#[from] crate::domain::path::PathError),
}

pub struct GuestVm;

pub struct GuestVmState {
    report: DerivedActorRef<GuestVmObservation>,
    running: Option<JoinHandle<()>>,
}

impl Actor for GuestVm {
    type Msg = GuestVmCommand;
    type State = GuestVmState;
    type Arguments = DerivedActorRef<GuestVmObservation>;

    fn pre_start(
        &self,
        _myself: ActorRef<GuestVmCommand>,
        report: DerivedActorRef<GuestVmObservation>,
    ) -> impl Future<Output = Result<GuestVmState, ActorProcessingErr>> + Send {
        std::future::ready(Ok(GuestVmState {
            report,
            running: None,
        }))
    }

    fn handle(
        &self,
        _myself: ActorRef<GuestVmCommand>,
        message: GuestVmCommand,
        state: &mut GuestVmState,
    ) -> impl Future<Output = Result<(), ActorProcessingErr>> + Send {
        if let Some(running) = state.running.take() {
            running.abort();
        }
        let report = state.report.clone();
        state.running = Some(tokio::spawn(async move {
            let observation = run(message).await;
            if report.send_message(observation).is_err() {
                tracing::debug!("guest result undeliverable: the twin stopped");
            }
        }));
        std::future::ready(Ok(()))
    }

    fn post_stop(
        &self,
        _myself: ActorRef<GuestVmCommand>,
        state: &mut GuestVmState,
    ) -> impl Future<Output = Result<(), ActorProcessingErr>> + Send {
        if let Some(running) = state.running.take() {
            running.abort();
        }
        std::future::ready(Ok(()))
    }
}

async fn run(command: GuestVmCommand) -> GuestVmObservation {
    match command {
        GuestVmCommand::Prepare {
            generation,
            vm,
            spec,
            seed_own_config,
        } => match prepare(&vm, &spec, seed_own_config).await {
            Ok((port, host_key)) => GuestVmObservation::Prepared {
                generation,
                port,
                host_key,
            },
            Err(error) => GuestVmObservation::PrepareFailed {
                generation,
                reason: Report::of(&error),
            },
        },
        GuestVmCommand::AwaitSsh {
            generation,
            port,
            timeout_seconds,
        } => {
            let deadline =
                tokio::time::Instant::now() + Duration::from_secs(u64::from(timeout_seconds));
            loop {
                if ssh::banner(port).await {
                    break GuestVmObservation::SshReady { generation };
                }
                if tokio::time::Instant::now() >= deadline {
                    break GuestVmObservation::SshTimedOut { generation };
                }
                tokio::time::sleep(PROBE_INTERVAL).await;
            }
        }
    }
}

async fn prepare(
    vm: &VmPaths,
    spec: &VmSpec,
    seed_own_config: bool,
) -> Result<(LoopbackPort, HostPublicKey), GuestVmError> {
    let host_key = ssh::ensure_host_key(vm).await?;
    let guest = GuestTree::open(&vm.guest())?;
    guest.ensure_directory(&RelativePath::parse("home")?)?;
    guest.replace_file(
        &RelativePath::parse("ssh_host_ed25519_key")?,
        &files::read_bytes(&vm.host_key())?,
        0o600,
    )?;
    guest.replace_file(
        &RelativePath::parse("mounts")?,
        plan::files::mounts_table(&spec.shares).as_bytes(),
        0o644,
    )?;
    guest.replace_file(
        &RelativePath::parse("hostname")?,
        format!("{}\n", vm.name()).as_bytes(),
        0o644,
    )?;
    // No terminal is ever attached, so no size to pass on.
    guest.remove_file(&RelativePath::parse("term")?)?;
    copy_home_files(&guest, spec)?;
    let mut config = files::read_tree(&vm.nix_config())?;
    config.insert(
        RelativePath::parse("host.nix")?,
        files::read_bytes(&vm.host_module())?,
    );
    if seed_own_config {
        guest.replace_tree(&RelativePath::parse(GUEST_OWN_CONFIG)?, &config)?;
    }
    guest.replace_tree(&RelativePath::parse(GUEST_REFERENCE_CONFIG)?, &config)?;
    guest.replace_file(
        &RelativePath::parse(GUEST_CONFIG_DIRECTORY)?.join(&RelativePath::parse("README.md")?),
        GUEST_README.as_bytes(),
        0o644,
    )?;
    let port = match spec.ssh_port {
        Some(port) => port,
        None => ssh::free_port()?,
    };
    Ok((port, host_key))
}

/// The configured files under the host user's home, copied into the guest's home (the guest
/// home has the host home's path; its contents live under `home/` in the guest directory).
/// The host copy wins on every start; a missing file is skipped with a warning.
fn copy_home_files(guest: &GuestTree, spec: &VmSpec) -> Result<(), GuestVmError> {
    let host_home = AbsolutePath::parse(spec.account.home.as_str().into())?;
    let guest_home = RelativePath::parse("home")?;
    for file in &spec.home_files {
        if let Some((bytes, mode)) = files::read_regular_file(&host_home.join_relative(file))? {
            guest.replace_file(&guest_home.join(file), &bytes, mode)?;
        } else {
            tracing::warn!(
                file = file.as_str(),
                "not copying a home file into the VM: no such file"
            );
        }
    }
    Ok(())
}

impl crate::diagnostic::Diagnostic for GuestVmError {
    fn code(&self) -> &'static str {
        match self {
            Self::Ssh(inner) => inner.code(),
            Self::Guest(inner) => inner.code(),
            Self::File(inner) => inner.code(),
            Self::Path(inner) => inner.code(),
            Self::Home(inner) => inner.code(),
        }
    }
    fn hint(&self) -> Option<String> {
        match self {
            Self::Ssh(inner) => inner.hint(),
            Self::Guest(inner) => inner.hint(),
            Self::File(inner) => inner.hint(),
            Self::Path(inner) => inner.hint(),
            Self::Home(inner) => inner.hint(),
        }
    }
}

#[cfg(test)]
mod tests {
    #![allow(
        clippy::disallowed_types,
        reason = "test fixtures build raw temp paths"
    )]

    use tokio::io::AsyncWriteExt as _;

    use super::*;
    use crate::domain::account::{GroupId, GuestHome, UserId, UserName};
    use crate::domain::path::AbsolutePath;
    use crate::domain::share::Shares;
    use crate::domain::vm_name::VmName;
    use crate::runtime::paths::RuntimePaths;
    use crate::vm::{Account, NixConfig, bundled};

    struct Fixture {
        _temporary: tempfile::TempDir,
        vm: VmPaths,
        guest_vm: ActorRef<GuestVmCommand>,
        observations: tokio::sync::mpsc::UnboundedReceiver<GuestVmObservation>,
    }

    async fn fixture() -> Fixture {
        let temporary = tempfile::tempdir().unwrap();
        let root = AbsolutePath::parse(temporary.path().to_path_buf()).unwrap();
        let paths = RuntimePaths::under(root.join("data"), root.join("run")).unwrap();
        let vm = paths.vm(&VmName::parse("work".into()).unwrap()).unwrap();
        // What the Builder leaves behind.
        files::replace_directory(&vm.nix_config(), &bundled::config()).unwrap();
        files::write_atomically(&vm.host_module(), b"# host\n", 0o644).unwrap();
        let (twin, observations) = crate::testing::probe::<GuestVmObservation>().await;
        let (guest_vm, _) = Actor::spawn(None, GuestVm, twin.get_derived())
            .await
            .unwrap();
        Fixture {
            _temporary: temporary,
            vm,
            guest_vm,
            observations,
        }
    }

    fn spec() -> VmSpec {
        VmSpec {
            shares: Shares::default(),
            account: Account {
                user: UserName::parse("alice".into()).unwrap(),
                user_id: UserId::new(1000),
                group_id: GroupId::new(100),
                home: GuestHome::parse("/home/alice".into()).unwrap(),
            },
            nix_config: NixConfig::Existing,
            boot_timeout_seconds: 60,
            powerdown_grace_seconds: 30,
            home_files: Vec::new(),
            ssh_port: None,
        }
    }

    async fn next(fixture: &mut Fixture) -> GuestVmObservation {
        tokio::time::timeout(Duration::from_secs(10), fixture.observations.recv())
            .await
            .unwrap()
            .unwrap()
    }

    fn prepare(fixture: &Fixture, seed_own_config: bool) {
        fixture
            .guest_vm
            .cast(GuestVmCommand::Prepare {
                generation: Generation::FIRST,
                vm: fixture.vm.clone(),
                spec: Box::new(spec()),
                seed_own_config,
            })
            .unwrap();
    }

    #[tokio::test]
    async fn prepare_writes_the_guest_files_and_seeds_the_own_config_only_when_asked() {
        let mut fixture = fixture().await;
        prepare(&fixture, true);
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::Prepared { .. }
        ));
        let guest = fixture.vm.guest();
        let read = |relative: &str| std::fs::read(guest.as_path().join(relative)).unwrap();
        assert_eq!(read("hostname"), b"work\n");
        assert_eq!(read("mounts"), b"");
        assert_eq!(read("home/amoeboid/nix/host.nix"), b"# host\n");
        assert_eq!(
            read("home/amoeboid/reference/flake.nix"),
            read("home/amoeboid/nix/flake.nix")
        );
        assert_eq!(
            read("ssh_host_ed25519_key"),
            files::read_bytes(&fixture.vm.host_key()).unwrap()
        );

        // The guest edits its own copy; a later start without seeding leaves it alone.
        let own = guest.as_path().join("home/amoeboid/nix/recipe.nix");
        std::fs::write(&own, b"guest edit").unwrap();
        prepare(&fixture, false);
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::Prepared { .. }
        ));
        assert_eq!(std::fs::read(&own).unwrap(), b"guest edit");
    }

    #[tokio::test]
    async fn await_ssh_reports_ready_on_a_banner_and_times_out_without_one() {
        let mut fixture = fixture().await;
        let listener = tokio::net::TcpListener::bind(("127.0.0.1", 0))
            .await
            .unwrap();
        let port = LoopbackPort::new(
            std::num::NonZeroU16::new(listener.local_addr().unwrap().port()).unwrap(),
        );
        let server = tokio::spawn(async move {
            let (mut stream, _) = listener.accept().await.unwrap();
            stream.write_all(b"SSH-2.0-test\r\n").await.unwrap();
        });
        let await_ssh = |port, timeout_seconds| GuestVmCommand::AwaitSsh {
            generation: Generation::FIRST,
            port,
            timeout_seconds,
        };
        fixture.guest_vm.cast(await_ssh(port, 5)).unwrap();
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::SshReady { .. }
        ));
        server.await.unwrap();
        // Nothing listens there any more.
        fixture.guest_vm.cast(await_ssh(port, 1)).unwrap();
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::SshTimedOut { .. }
        ));
    }

    #[tokio::test]
    async fn home_files_are_copied_with_their_mode_and_missing_ones_skipped() {
        use std::os::unix::fs::PermissionsExt as _;
        let mut fixture = fixture().await;
        // Under target/: a guest home may not lie under /tmp.
        let target = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../target")
            .canonicalize()
            .unwrap();
        let home = tempfile::tempdir_in(target).unwrap();
        std::fs::create_dir_all(home.path().join(".config/git")).unwrap();
        std::fs::write(home.path().join(".config/git/config"), "[user]\n").unwrap();
        std::fs::set_permissions(
            home.path().join(".config/git/config"),
            std::fs::Permissions::from_mode(0o640),
        )
        .unwrap();
        let mut spec = spec();
        spec.account.home = GuestHome::parse(home.path().to_str().unwrap().into()).unwrap();
        spec.home_files = vec![
            RelativePath::parse(".config/git/config").unwrap(),
            RelativePath::parse(".missing").unwrap(),
        ];
        fixture
            .guest_vm
            .cast(GuestVmCommand::Prepare {
                generation: Generation::FIRST,
                vm: fixture.vm.clone(),
                spec: Box::new(spec),
                seed_own_config: true,
            })
            .unwrap();
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::Prepared { .. }
        ));
        let copied = fixture.vm.guest().as_path().join("home/.config/git/config");
        assert_eq!(std::fs::read(&copied).unwrap(), b"[user]\n");
        assert_eq!(
            std::fs::metadata(&copied).unwrap().permissions().mode() & 0o777,
            0o640
        );
        assert!(!fixture.vm.guest().as_path().join("home/.missing").exists());
    }

    #[tokio::test]
    async fn a_configured_port_is_used_instead_of_a_free_one() {
        let mut fixture = fixture().await;
        let mut spec = spec();
        let wanted = LoopbackPort::new(std::num::NonZeroU16::new(40_123).unwrap());
        spec.ssh_port = Some(wanted);
        fixture
            .guest_vm
            .cast(GuestVmCommand::Prepare {
                generation: Generation::FIRST,
                vm: fixture.vm.clone(),
                spec: Box::new(spec),
                seed_own_config: false,
            })
            .unwrap();
        assert!(matches!(
            next(&mut fixture).await,
            GuestVmObservation::Prepared { port, .. } if port == wanted
        ));
    }
}

//! `GuestVm`: everything about the guest side of a VM. Prepares what the guest reads at boot
//! (host key copy, `mounts`, `hostname`, Nix config copies, README) through guest delivery,
//! pins the host key, picks the forwarded port, and later waits for sshd. Stateless: each
//! command runs in a task, and a newer command replaces a running one.
//!
//! Nothing is read back from the guest directory: whether to seed the guest's own config copy
//! is the twin's decision (`seed_own_config`), not a look at what the guest has.

use std::time::Duration;

use ractor::{Actor, ActorProcessingErr, ActorRef, DerivedActorRef};

//! Files generated for a VM: the guest's `mounts` table, `host.nix`, and the `known_hosts` line
//! that pins the guest's host key.

use super::share::tag;
use crate::domain::account::{GroupId, GuestHome, UserId, UserName};
use crate::domain::host_key::HostPublicKey;
use crate::domain::share::Shares;
use crate::domain::vm_name::VmName;

/// The guest's `mounts` file: `<tag>\t<mode>\t<path>\n` per share, in mount order. Read by a
/// shell loop in the guest (`nix/base.nix`).
#[must_use]
pub fn mounts_table(shares: &Shares) -> String {
    use std::fmt::Write as _;
    let mut table = String::new();
    for (index, share) in shares.as_slice().iter().enumerate() {
        // Writing to a String can't fail.
        let _ = writeln!(
            table,
            "{}\t{}\t{}",
            tag(index),
            share.mode.as_str(),
            share.directory.as_str()
        );
    }
    table
}

/// A Nix string literal. Everything interpolated into generated Nix goes through this.
#[must_use]
pub fn nix_string(text: &str) -> String {
    let escaped = text
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace("${", "\\${");
    format!("\"{escaped}\"")
}

/// The flake's `host` input: the guest account, mirroring the host user.
#[must_use]
pub fn host_module(
    user: &UserName,
    user_id: UserId,
    group_id: GroupId,
    home: &GuestHome,
) -> String {
    format!(
        "# Generated by amoeboid on every start; edits here are lost.\n\
         {{ ... }}:\n\
         \n\
         {{\n  \
           amoeboid.user = {};\n  \
           amoeboid.uid = {};\n  \
           amoeboid.gid = {};\n  \
           amoeboid.home = {};\n\
         }}\n",
        nix_string(user.as_str()),
        user_id.get(),
        group_id.get(),
        nix_string(home.as_str()),
    )
}

/// The VM's `known_hosts`: its host key under its alias.
#[must_use]
pub fn known_hosts(vm: &VmName, key: &HostPublicKey) -> String {
    format!(
        "{} {} {}\n",
        super::ssh_alias(vm),
        HostPublicKey::KIND,
        key.key()
    )
}
